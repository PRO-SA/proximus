export type TranslationKey = keyof typeof translations.no;

export function getTranslation(lang: Language, key: TranslationKey): string {
  return translations[lang][key];
}

export function detectLanguage(): Language {
  if (typeof window === 'undefined') return 'no';

  const stored = localStorage.getItem('janus-lang');
  if (stored === 'no' || stored === 'en') return stored;

  const browserLang = navigator.language.toLowerCase();
  if (browserLang.startsWith('nb') || browserLang.startsWith('nn') || browserLang.startsWith('no')) {
    return 'no';
  }

  return 'en';
}
